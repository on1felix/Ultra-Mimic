/** Typed translator for the redesigned screens. */
export function useUi() {
  const { language, t } = useI18n();
  const dict = language === 'ru' ? ru : en;

  const u = (key: UIKey, params?: Record<string, string | number>): string => {
    let template: string = dict[key];
    if (!params) return template;
    for (const [name, value] of Object.entries(params)) {
      template = template.split(`{${name}}`).join(String(value));
    }
    return template;
  };

  return { u, language, t, formatNumber: (value: number) => new Intl.NumberFormat(language === 'ru' ? 'ru-RU' : 'en-US').format(value) };
}
